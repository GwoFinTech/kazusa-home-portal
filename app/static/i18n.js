/* ── Core runtime ── */
let _locale = null;

function i18nDetect() {
  const saved = localStorage.getItem('lang');
  if (saved && I18N_LOCALES.includes(saved)) return saved;
  const nav = (navigator.language || 'zh-CN');
  for (const l of I18N_LOCALES) if (nav === l || nav.startsWith(l.split('-')[0])) return l;
  return 'zh-CN';
}

function t(key, params) {
  let s = (I18N_MESSAGES[_locale] && I18N_MESSAGES[_locale][key])
       || I18N_MESSAGES['zh-CN'][key]
       || key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
  }
  return s;
}

function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  document.documentElement.lang = _locale.replace('en-US', 'en');
}

function setLocale(lang, silent) {
  if (!I18N_LOCALES.includes(lang)) return;
  _locale = lang;
  localStorage.setItem('lang', lang);
  applyI18n();
  refreshIcons?.();
  if (!silent) window.dispatchEvent(new CustomEvent('i18n:change', { detail: { lang } }));
}

function currentLocale() { return _locale; }

/* Cycle button next to the theme toggle */
(function() {
  _locale = i18nDetect();
  document.addEventListener('DOMContentLoaded', () => {
    applyI18n();
    const btn = document.createElement('button');
    btn.className = 'theme-toggle lang-toggle';
    btn.style.right = '60px';
    btn.onclick = function() {
      const next = I18N_LOCALES[(I18N_LOCALES.indexOf(_locale) + 1) % I18N_LOCALES.length];
      setLocale(next);
      btn.textContent = I18N_LABELS[next];
      btn.title = next;
    };
    btn.textContent = I18N_LABELS[_locale];
    btn.title = _locale;
    btn.setAttribute('aria-label', 'language');
    document.body.appendChild(btn);
    refreshIcons?.();
  });
})();
